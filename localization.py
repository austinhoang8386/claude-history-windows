assert EN.keys() == VI.keys(), 'Translation keys must be identical'

def set_language(language: str) -> None:
    global CURRENT_LANGUAGE
    if language not in ('en', 'vi'):
        raise ValueError('Unsupported language: ' + str(language))
    CURRENT_LANGUAGE = language

def get_language() -> str:
    return CURRENT_LANGUAGE

def tr(key: str, **kwargs) -> str:
    string = (EN if CURRENT_LANGUAGE == 'en' else VI)[key]
    return string.format(**kwargs) if kwargs else string
